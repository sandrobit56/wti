function parseFlags(flags: string, parent: Dish): Pick<Variant, "vegetarian" | "vegan" | "spicy" | "heaviness" | "healthy"> {
  const bad = flags.replace(/[vVsSlhH]/g, "");
  if (bad) throw new Error(`variants: unknown flag(s) "${bad}"`);
  const vegan = flags.includes("V");
  return {
    vegan,
    vegetarian: vegan || flags.includes("v"),
    spicy: flags.includes("S") ? 2 : flags.includes("s") ? 1 : 0,
    heaviness: flags.includes("l") ? "მსუბუქი" : flags.includes("h") ? "მძიმე" : parent.heaviness,
    healthy: flags.includes("H"),
  };
}

export const MAX_VARIANTS_PER_TYPE = 20;

export const VARIANTS: Variant[] = DISHES.flatMap((parent) => {
  const rows = ROWS[parent.slug];
  if (!rows || rows.length === 0) throw new Error(`variants: dish type "${parent.slug}" has no variants`);
  if (rows.length > MAX_VARIANTS_PER_TYPE) throw new Error(`variants: "${parent.slug}" has ${rows.length} > ${MAX_VARIANTS_PER_TYPE}`);
  return rows.map(([slug, name, desc, min, max, flags, wiki]): Variant => {
    if (min > max) throw new Error(`variants: bad price ${parent.slug}/${slug}`);
    return { slug: `${parent.slug}/${slug}`, type: parent.slug, name, desc, priceGel: [min, max], wiki: wiki ?? null, ...parseFlags(flags, parent) };
  });
});

for (const t of Object.keys(ROWS)) if (!DISHES.some((d) => d.slug === t)) throw new Error(`variants: unknown dish type "${t}"`);
if (new Set(VARIANTS.map((v) => v.slug)).size !== VARIANTS.length) throw new Error("variants: duplicate slug");

const BY_TYPE = new Map<string, Variant[]>();
for (const v of VARIANTS) BY_TYPE.set(v.type, [...(BY_TYPE.get(v.type) ?? []), v]);

export function variantsOf(typeSlug: string): Variant[] {
  const list = BY_TYPE.get(typeSlug);
  if (!list) throw new Error(`variants: unknown type ${typeSlug}`);
  return list;
}
